func TestValidationErrors(t *testing.T) {
	cases := map[string]*Request{
		"one node":     {Nodes: []string{"a"}, EndTimeMs: 10},
		"dup nodes":    {Nodes: []string{"a", "a"}, EndTimeMs: 10},
		"bad end time": {Nodes: []string{"a", "b"}},
		"bad loss":     {Nodes: []string{"a", "b"}, EndTimeMs: 10, Network: PolicyRandom(1.2, 0, 1, 2)},
		"unknown broadcast node": {
			Nodes: []string{"a", "b"}, EndTimeMs: 10,
			Broadcasts: []BroadcastSpec{{AtMs: 0, Node: "z"}},
		},
		"bad topology edge": {
			Nodes: []string{"a", "b"}, EndTimeMs: 10,
			Topology: map[string][]string{"a": {"z"}, "b": {}},
		},
		"invalid fault action": {
			Nodes: []string{"a", "b"}, EndTimeMs: 10,
			Faults: faultList{{origin: "a", seq: 1, to: "b", action: "explode"}}.toFaults(),
		},
	}
	for name, req := range cases {
		t.Run(name, func(t *testing.T) {
			if r := Run(req); r.Status != "error" {
				t.Fatalf("%s: expected validation error, got %s (%s)", name, r.Status, r.Error)
			}
		})
	}
}
