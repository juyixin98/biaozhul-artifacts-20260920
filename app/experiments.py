"""Reproducibility experiments.

Loads the *hand-authored* fixture JSON files. The expected answers live in those
files (with their arithmetic derivations) -- they are authored, not generated by
the estimation core. This module only assembles requests and runs the service
pipeline so tests/scripts can compare core output against independent answers.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Any

from .contracts import DIDRequest, EventStudyRequest

FIXTURE_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "fixtures")

DID_FIXTURES = (
    "handcalc_2x2.json",
    "missing_period.json",
    "nonparallel_pretrend.json",
    "contamination.json",
)
EVENT_FIXTURES = (
    "event_single_cohort.json",
    "event_staggered_refused.json",
)


@dataclass(frozen=True)
class Fixture:
    case_id: str
    payload: dict[str, Any]
    expected: dict[str, Any]
    path: str


def load_fixture(filename: str) -> Fixture:
    path = os.path.join(FIXTURE_DIR, filename)
    with open(path, "r", encoding="utf-8") as fh:
        payload = json.load(fh)
    return Fixture(
        case_id=payload["case_id"],
        payload=payload,
        expected=payload.get("expected", {}),
        path=path,
    )


def all_did_fixtures() -> list[Fixture]:
    return [load_fixture(name) for name in DID_FIXTURES]


def all_event_fixtures() -> list[Fixture]:
    return [load_fixture(name) for name in EVENT_FIXTURES]


def to_did_request(fixture: Fixture) -> DIDRequest:
    p = fixture.payload
    return DIDRequest(
        request_id=f"fixture:{fixture.case_id}",
        observations=p["observations"],
        pre_period=p["pre_period"],
        post_period=p["post_period"],
        earlier_period=p.get("earlier_period"),
        include_reference_regression=True,
    )


def to_event_request(fixture: Fixture) -> EventStudyRequest:
    p = fixture.payload
    return EventStudyRequest(
        request_id=f"fixture:{fixture.case_id}",
        observations=p["observations"],
        min_event_time=p["min_event_time"],
        max_event_time=p["max_event_time"],
    )
