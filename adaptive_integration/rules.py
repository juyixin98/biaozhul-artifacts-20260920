# Gauss 7 点权值，放在与 _XK 相同的 15 个下标上：
# Gauss 节点是 _XK 的第 1,3,5,...,13 下标（0 基），其余位置为 0。
_WG = np.zeros(15)
_WG_IDX = (1, 3, 5, 7, 9, 11, 13)
_WG[list(_WG_IDX)] = np.array(
    [
        0.129484966168869693270611432679082,
        0.279705391489276667901467771423780,
        0.381830050505118944950369775488975,
        0.417959183673469387755102040816327,
        0.381830050505118944950369775488975,
        0.279705391489276667901467771423780,
        0.129484966168869693270611432679082,
    ]
)

_MACHEP = np.finfo(float).eps  # 2.22e-16


def gk15_rule(f, a: float, b: float):
    """在 [a,b] 上做一次 7-15 Gauss-Kronrod 求积。

    参数
    ----
    f : 接受 NumPy 数组的被积函数（异常值由调用方检测）

    返回
    ----
    (resk, err, resabs, resasc)
        resk   Kronrod 积分近似
        err    误差估计（非负，已含舍入底噪保护）
        resabs 对 |f| 的 Kronrod 近似（绝对误差量纲）
        resasc 对 |f - 区间均值| 的 Kronrod 近似（振荡量纲）
    """

    center = 0.5 * (a + b)
    half = 0.5 * (b - a)
    x = center + half * _XK
    fv = np.asarray(f(x), dtype=float)

    resk = half * np.sum(_WK * fv)
    resg = half * np.sum(_WG * fv)
    resabs = half * np.sum(np.abs(_WK * fv))
    mean = 0.5 * resk / half if half != 0.0 else 0.0
    resasc = half * np.sum(np.abs(_WK * (fv - mean)))

    err = abs(resk - resg)
    # QUADPACK 的保守修正：振荡/绝对占优时差值估计过于乐观，
    # 用 resasc 抬高估计；resasc==0（常数被积函数）时保持差值。
    if resasc != 0.0 and err != 0.0:
        scale = min(1.0, (200.0 * err / resasc) ** 1.5)
        err = resasc * scale
    # 舍入底噪保护：被积函数很大时规则本身的舍入不可忽略
    floor = 50.0 * _MACHEP * resabs
    floor_hit = False
    if err < floor:
        err = floor
        floor_hit = True
    return resk, err, resabs, resasc, floor_hit
