"""Numerical verification.

This module is the *independent oracle* used by tests. Nothing here calls the
integer kernel or the graph - answers must not be generated by the code under
test.

Two independent references are provided:

* :func:`float_reference` - plain float64 evaluation of the trained model
  (the value the quantized engine is compared against; equality is not
  required, bounded error is).
* :func:`exact_integer_reference` - a pure-Python, arbitrary-precision
  reimplementation of the integer pipeline (explicit ``int`` dot products,
  explicit rounding and saturation), used to assert the kernel's *exact*
  element-wise integer results on hand-computable cases.

Analytic per-output-channel error bounds are derived from each independent
rounding stage (input, weights, bias, output), so tests assert "error is
within the analytic bound", not "smaller than a magic tolerance".
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any

import numpy as np

from .model import QuantizedModelArtifact, TrainedModel
from .tensor_types import PerChannelQParams, QParams, dtype_bounds


# ---------------------------------------------------------------------------
# Independent rounding / encoding (no reuse of engine.quantize internals).
# ---------------------------------------------------------------------------


def round_half_away_scalar(x: float) -> int:
    """Round-half-away-from-zero via Python integer arithmetic."""
    if not math.isfinite(x):
        raise ValueError("cannot round a non-finite value")
    if x >= 0.0:
        return int(math.floor(x + 0.5))
    return -int(math.floor(-x + 0.5))


def _encode_scalar(
    value: float, scale: float, zero_point: int, dtype: Any
) -> int:
    qmin, qmax = dtype_bounds(np.dtype(dtype))
    q = round_half_away_scalar(value / scale) + zero_point
    return max(qmin, min(qmax, q))


def _saturate_scalar(q: int, dtype: Any) -> int:
    qmin, qmax = dtype_bounds(np.dtype(dtype))
    return max(qmin, min(qmax, q))


# ---------------------------------------------------------------------------
# Float64 reference of the trained model (independent plain evaluation).
# ---------------------------------------------------------------------------


def float_reference(
    trained: TrainedModel, x: np.ndarray, *, hidden_relu: bool = True
) -> np.ndarray:
    """Plain float64 forward pass; the comparison target (not equality)."""
    cur = np.asarray(x, dtype=np.float64).copy()
    last = len(trained.weights) - 1
    for i, (w, b) in enumerate(zip(trained.weights, trained.biases)):
        cur = cur @ np.asarray(w, dtype=np.float64).T + np.asarray(
            b, dtype=np.float64
        )
        if i != last and hidden_relu:
            cur = np.maximum(cur, 0.0)
    return cur


# ---------------------------------------------------------------------------
# Exact arbitrary-precision integer reference.
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ExactLayerTrace:
    """Per-layer exact trace, for element-wise assertions in tests."""

    q_input: list[list[int]]
    accumulator: list[list[int]]  # zero-point-corrected MAC, no bias
    biased: list[list[int]]  # MAC + quantized bias
    q_output: list[list[int]]
    saturated: list[list[bool]]
    real_output: list[list[float]]


@dataclass(frozen=True)
class ExactTrace:
    layers: tuple[ExactLayerTrace, ...]

    @property
    def q_output(self) -> list[list[int]]:
        return self.layers[-1].q_output

    @property
    def real_output(self) -> list[list[float]]:
        return self.layers[-1].real_output


def _layer_integer_exact(
    x_real: list[list[float]],
    in_params: QParams,
    w_int: list[list[int]],
    w_params: PerChannelQParams,
    bias_q: list[int],
    out_params: QParams | PerChannelQParams,
) -> tuple[ExactLayerTrace, list[list[float]], list[list[int]]]:
    """One layer in pure Python big ints with explicit rounding/saturation."""
    batch = len(x_real)
    out_features = len(w_int)

    qx = [
        [
            _encode_scalar(v, in_params.scale, in_params.zero_point, in_params.dtype)
            for v in row
        ]
        for row in x_real
    ]

    channels = out_features
    if isinstance(out_params, PerChannelQParams):
        out_scales = list(out_params.scales)
        out_zps = [int(z) for z in out_params.zero_points]
        out_dtype = out_params.dtype
    else:
        out_scales = [out_params.scale] * channels
        out_zps = [out_params.zero_point] * channels
        out_dtype = out_params.dtype

    w_scales = list(w_params.scales)
    w_zps = [int(z) for z in w_params.zero_points]

    accumulator: list[list[int]] = []
    biased: list[list[int]] = []
    q_output: list[list[int]] = []
    saturated: list[list[bool]] = []
    real_output: list[list[float]] = []

    for bb in range(batch):
        acc_row: list[int] = []
        biased_row: list[int] = []
        q_row: list[int] = []
        sat_row: list[bool] = []
        real_row: list[float] = []
        for o in range(out_features):
            mac = 0
            for k, qx_bk in enumerate(qx[bb]):
                a = qx_bk - in_params.zero_point
                wdev = w_int[o][k] - w_zps[o]
                mac += a * wdev
            total = mac + bias_q[o]
            multiplier = in_params.scale * w_scales[o] / out_scales[o]
            q_real = total * multiplier
            q = round_half_away_scalar(q_real) + out_zps[o]
            qmin, qmax = dtype_bounds(out_dtype)
            is_sat = q < qmin or q > qmax
            q_sat = _saturate_scalar(q, out_dtype)
            real = out_scales[o] * (q_sat - out_zps[o])
            acc_row.append(mac)
            biased_row.append(total)
            q_row.append(q_sat)
            sat_row.append(is_sat)
            real_row.append(real)
        accumulator.append(acc_row)
        biased.append(biased_row)
        q_output.append(q_row)
        saturated.append(sat_row)
        real_output.append(real_row)

    trace = ExactLayerTrace(
        q_input=qx,
        accumulator=accumulator,
        biased=biased,
        q_output=q_output,
        saturated=saturated,
        real_output=real_output,
    )
    return trace, real_output, q_output


def exact_integer_reference(
    artifact: QuantizedModelArtifact, x: np.ndarray
) -> ExactTrace:
    """Recompute the artifact's integer graph in arbitrary precision.

    Encodes each layer's real activations with *that layer's* output params
    (the same params the graph uses when re-encoding between layers), so this
    mirrors the graph faithfully without sharing any of its code.
    """
    x_real = [[float(v) for v in row] for row in np.asarray(x, dtype=np.float64)]
    traces: list[ExactLayerTrace] = []
    cur_real = x_real
    cur_params: QParams = artifact.input_params
    for layer in artifact.layers:
        wm = layer.weight
        trace, cur_real, _ = _layer_integer_exact(
            cur_real,
            cur_params,
            [[int(v) for v in row] for row in wm.weights_int],
            wm.params,
            [int(v) for v in layer.bias_q],
            layer.output_params,
        )
        if layer.apply_relu:
            # ReLU in the integer domain at the encoded zero.
            if isinstance(layer.output_params, PerChannelQParams):
                zps = [int(z) for z in layer.output_params.zero_points]
                scales = list(layer.output_params.scales)
            else:
                zps = [layer.output_params.zero_point] * len(trace.q_output[0])
                scales = [layer.output_params.scale] * len(zps)
            q_relu = [
                [max(q, zps[o]) for o, q in enumerate(row)]
                for row in trace.q_output
            ]
            real_relu = [
                [scales[o] * (q - zps[o]) for o, q in enumerate(row)]
                for row in q_relu
            ]
            trace = ExactLayerTrace(
                q_input=trace.q_input,
                accumulator=trace.accumulator,
                biased=trace.biased,
                q_output=q_relu,
                saturated=trace.saturated,
                real_output=real_relu,
            )
            cur_real = real_relu
        traces.append(trace)
        is_last = layer is artifact.layers[-1]
        if not is_last:
            # Hidden layers are calibrated per-tensor by construction; the
            # next layer re-encodes against exactly those frozen params.
            if not isinstance(layer.output_params, QParams):
                raise AssertionError(
                    "hidden activations must be per-tensor QParams; "
                    "engine calibration guarantees this"
                )
            cur_params = layer.output_params
    return ExactTrace(layers=tuple(traces))


