# Error metrics.
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ErrorReport:
    """Comparison of engine output against the float reference."""

    max_abs_error: float
    mean_abs_error: float
    rmse: float
    max_rel_error: float
    per_channel_max_abs: list[float]
    within_analytic_bound: bool
    analytic_bound_per_channel: list[float]
    saturated_fraction: float
    bound_checked_elements: int
    bound_violations: int
    hidden_saturation: bool

    def to_dict(self) -> dict[str, Any]:
        return {
            "max_abs_error": self.max_abs_error,
            "mean_abs_error": self.mean_abs_error,
            "rmse": self.rmse,
            "max_rel_error": self.max_rel_error,
            "per_channel_max_abs": self.per_channel_max_abs,
            "within_analytic_bound": self.within_analytic_bound,
            "analytic_bound_per_channel": self.analytic_bound_per_channel,
            "saturated_fraction": self.saturated_fraction,
            "bound_checked_elements": self.bound_checked_elements,
            "bound_violations": self.bound_violations,
            "hidden_saturation": self.hidden_saturation,
        }


def error_report(
    engine_output: np.ndarray,
    float_output: np.ndarray,
    artifact: QuantizedModelArtifact,
    saturated: np.ndarray | None = None,
    *,
    hidden_saturation: bool = False,
) -> ErrorReport:
    """Compare the quantized engine against the float64 reference.

    Equality is not expected; the report records the observed error and
    whether it respects the analytic per-channel bound. The analytic bound
    applies to non-saturated final elements - a saturated final element is
    clipped by design, so its error is reported separately via
    ``saturated_fraction`` rather than counted as a bound violation.

    If a *hidden* activation saturated, its clipping error is not covered by
    the composed bound, so ``within_analytic_bound`` is forced false and the
    caller must render INDETERMINATE rather than certify the result.
    """
    engine_output = np.asarray(engine_output, dtype=np.float64)
    float_output = np.asarray(float_output, dtype=np.float64)
    if engine_output.shape != float_output.shape:
        raise ValueError(
            f"shape mismatch: {engine_output.shape} vs {float_output.shape}"
        )
    diff = engine_output - float_output
    abs_err = np.abs(diff)
    per_channel = [float(v) for v in abs_err.max(axis=0)]
    denom = np.maximum(np.abs(float_output), 1e-8)
    rel = abs_err / denom

    bounds = np.asarray(analytic_output_bound(artifact), dtype=np.float64)
    bounds_2d = np.broadcast_to(bounds, abs_err.shape)
    mask = (
        np.ones_like(abs_err, dtype=bool)
        if saturated is None
        else ~np.asarray(saturated, dtype=bool)
    )
    violations = int(np.count_nonzero(abs_err[mask] > bounds_2d[mask] + 1e-9))
    sat_fraction = float(np.mean(saturated)) if saturated is not None else 0.0
    within = (violations == 0) and not hidden_saturation
    return ErrorReport(
        max_abs_error=float(abs_err.max()),
        mean_abs_error=float(abs_err.mean()),
        rmse=float(np.sqrt(np.mean(diff**2))),
        max_rel_error=float(rel.max()),
        per_channel_max_abs=per_channel,
        within_analytic_bound=within,
        analytic_bound_per_channel=[float(v) for v in bounds],
        saturated_fraction=sat_fraction,
        bound_checked_elements=int(mask.sum()),
        bound_violations=violations,
        hidden_saturation=bool(hidden_saturation),
    )


def _layer_error_bound(
    in_params: QParams,
    w_dev: np.ndarray,
    w_scales: np.ndarray,
    s_out: np.ndarray,
    b_in: np.ndarray,
) -> np.ndarray:
    """Per-channel real-error bound at one layer's output.

    Exact decomposition (per output channel ``o``)::

        pre_o = sum_k w_hat_o,k * x_hat_k + b_hat_o     # accumulator domain
        y_hat_o = s_out_o * round(pre_o / s_out_o)      # output encode

        |y_hat - y| <=
            s_out_o / 2                                   # output rounding
          + s_in s_w_o / 2                                # bias rounding
          + s_w_o / 2 * sum_k |x_k|                       # weight rounding
          + s_w_o * sum_k |w_dev_o,k| * b_in[k]           # input error

    where ``b_in[k]`` is the real error bound on input element ``k`` (the
    layer-1 request encoding error is ``s_x/2``; between layers the hidden
    dequantize/requantize round-trips exactly, so no extra half-step is
    added). ``|x_k|`` is bounded by the frozen input params' representable
    magnitude ``s_in * x_dev_max`` - calibration range, not request data.
    """
    k_dim = w_dev.shape[1]
    qmin, qmax = dtype_bounds(in_params.dtype)
    x_dev_max = max(
        abs(qmin - in_params.zero_point), abs(qmax - in_params.zero_point)
    )
    x_max_real = in_params.scale * x_dev_max
    input_propagation = w_scales * (np.abs(w_dev) @ b_in)
    bound = (
        s_out * 0.5
        + in_params.scale * w_scales * 0.5
        + w_scales * 0.5 * k_dim * x_max_real
        + input_propagation
    )
    return bound


def analytic_output_bound(artifact: QuantizedModelArtifact) -> list[float]:
    """Conservative per-channel bound on |engine output - float output|.

    Bounds are composed layer by layer. The bound entering layer 1 is the
    request encoding error ``s_x/2`` per element; each layer adds its own
    weight/bias/output rounding error and propagates the incoming error
    through its (reconstructed) weights. ReLU is 1-Lipschitz, so it never
    increases the bound. Hidden-layer saturation invalidates the bound (the
    clipping error is not modeled here) - callers check that separately.
    """
    layers = artifact.layers
    b_in = np.full(
        int(artifact.architecture[0]),
        artifact.input_params.scale * 0.5,
        dtype=np.float64,
    )
    in_params = artifact.input_params
    bound = np.zeros(0, dtype=np.float64)
    for layer in layers:
        wparams = layer.weight.params
        w_dev = (
            layer.weight.weights_int.astype(np.int64)
            - wparams.zero_points[:, None]
        )
        out_params = layer.output_params
        if isinstance(out_params, PerChannelQParams):
            s_out = out_params.scales
        else:
            s_out = np.full(w_dev.shape[0], out_params.scale, dtype=np.float64)
        bound = _layer_error_bound(
            in_params, w_dev, wparams.scales, s_out, b_in
        )
        if not isinstance(out_params, QParams):
            # Final per-channel output: no further layer to feed.
            break
        # The next layer consumes this activation; dequantize followed by
        # requantization with the same params is an exact round trip, so the
        # per-channel bound carries over unchanged as its input error.
        in_params = out_params
        b_in = bound
    return [float(v) for v in bound]
