"""Independent reference oracle built with plain brute force.

This module deliberately imports nothing from :mod:`app.solver`. It takes
plain dictionaries/lists (the JSON-shaped model payload) and enumerates every
complete assignment with :func:`itertools.product`. Tests cross-check the
solver kernel against it, so the reference answer is not generated by the
code under test.
"""

from __future__ import annotations

import itertools
from collections.abc import Callable
from typing import Any

_COMPARISONS: dict[str, Callable[[int, int], bool]] = {
    "eq": lambda a, b: a == b,
    "ne": lambda a, b: a != b,
    "lt": lambda a, b: a < b,
    "le": lambda a, b: a <= b,
    "gt": lambda a, b: a > b,
    "ge": lambda a, b: a >= b,
}


def _relation_holds(relation: dict[str, Any], a: int, b: int) -> bool:
    kind = relation["kind"]
    if kind == "comparison":
        return _COMPARISONS[relation["op"]](a, b)
    pairs = {tuple(pair) for pair in relation.get("pairs", [])}
    if kind == "allowed":
        return (a, b) in pairs
    return (a, b) not in pairs


def _assignment_satisfies(model: dict[str, Any], assignment: dict[str, int]) -> bool:
    for constraint in model.get("binary_constraints", []):
        a = assignment[constraint["left"]]
        b = assignment[constraint["right"]]
        if not _relation_holds(constraint["relation"], a, b):
            return False
    for group in model.get("all_different", []):
        values = [assignment[variable] for variable in group]
        if len(values) != len(set(values)):
            return False
    return True


def enumerate_solutions(
    model: dict[str, Any], limit: int | None = None
) -> list[dict[str, int]]:
    """All satisfying complete assignments (optionally capped)."""
    variables = list(model["domains"])
    solutions: list[dict[str, int]] = []
    for combination in itertools.product(
        *(model["domains"][variable] for variable in variables)
    ):
        assignment = dict(zip(variables, combination))
        if _assignment_satisfies(model, assignment):
            solutions.append(assignment)
            if limit is not None and len(solutions) >= limit:
                break
    return solutions


def count_solutions(model: dict[str, Any]) -> int:
    return len(enumerate_solutions(model))


def viable_values(model: dict[str, Any]) -> dict[str, set[int]]:
    """The set of values each variable takes across *all* solutions.

    Sound propagation must never prune a value in this set.
    """
    viable: dict[str, set[int]] = {
        variable: set() for variable in model["domains"]
    }
    for solution in enumerate_solutions(model):
        for variable, value in solution.items():
            viable[variable].add(value)
    return viable


def satisfiability(model: dict[str, Any]) -> str:
    """Return ``"sat"`` or ``"unsat"`` by complete enumeration."""
    return "sat" if enumerate_solutions(model, limit=1) else "unsat"
