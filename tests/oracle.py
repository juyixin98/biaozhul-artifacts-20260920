"""Independent brute-force reference oracle.

NOTHING from ``app.miner`` is imported here on purpose.  The reference answers
are generated by a deliberately simple, independent algorithm:

1. enumerate every strictly-increasing position tuple of a sequence;
2. accept it iff its symbols equal the candidate pattern and every consecutive
   pair satisfies the declared gaps (position gap = index distance, adjacent =
   1; time gap = timestamp difference, 0 for equal timestamps);
3. support = the set of *distinct sequence ids* having >= 1 accepted tuple.

Candidate patterns are grown only over symbols that themselves clear
``min_support`` (the Apriori fact "every symbol of a frequent pattern is
frequent"), but support itself is always recomputed by the brute-force
embedding enumeration above, so this pruning cannot manufacture agreement
with the projection engine.
"""
from __future__ import annotations

from collections.abc import Callable
from typing import Optional

Seq = list[tuple[str, Optional[float]]]


def pair_legal(q_pos: int, p_pos: int,
               t_q: Optional[float], t_p: Optional[float],
               max_gap_position: Optional[int],
               max_gap_time: Optional[float]) -> bool:
    """Independent restatement of the declared pair semantics."""
    if p_pos <= q_pos:
        return False
    if max_gap_position is not None and (p_pos - q_pos) > max_gap_position:
        return False
    if max_gap_time is not None:
        if t_q is None or t_p is None:
            return False
        if (t_p - t_q) > max_gap_time:
            return False
    return True


def brute_embeddings(seq: Seq, pattern: tuple[str, ...],
                     max_gap_position: Optional[int] = None,
                     max_gap_time: Optional[float] = None) -> list[tuple[int, ...]]:
    """All position tuples matching ``pattern``, by exhaustive DFS."""
    found: list[tuple[int, ...]] = []
    path: list[int] = []

    def dfs(symbol_idx: int, start: int) -> None:
        if symbol_idx == len(pattern):
            found.append(tuple(path))
            return
        for pos in range(start, len(seq)):
            sym, ts = seq[pos]
            if sym != pattern[symbol_idx]:
                continue
            if path:
                q = path[-1]
                if not pair_legal(q, pos, seq[q][1], ts,
                                  max_gap_position, max_gap_time):
                    continue
            path.append(pos)
            dfs(symbol_idx + 1, pos + 1)
            path.pop()

    dfs(0, 0)
    return found


def brute_mine(sequences: dict[str, Seq], *, min_support: int,
               max_gap_position: Optional[int] = None,
               max_gap_time: Optional[float] = None,
               max_pattern_length: int = 64
               ) -> dict[tuple[str, ...], dict[str, list[tuple[int, ...]]]]:
    """Pattern -> {sequence_id: [embedding position tuples]} for frequent items.

    Returned only for patterns whose distinct supporting-sequence count is
    >= ``min_support``.
    """
    vocabulary = sorted({sym for seq in sequences.values() for sym, _ in seq})

    def support_of(pattern: tuple[str, ...]) -> dict[str, list[tuple[int, ...]]]:
        hits: dict[str, list[tuple[int, ...]]] = {}
        for sid, seq in sequences.items():
            emb = brute_embeddings(seq, pattern, max_gap_position, max_gap_time)
            if emb:
                hits[sid] = emb
        return hits

    frequent: dict[tuple[str, ...], dict[str, list[tuple[int, ...]]]] = {}
    seeds: list[tuple[str, ...]] = []
    for sym in vocabulary:
        hits = support_of((sym,))
        if len(hits) >= min_support:
            frequent[(sym,)] = hits
            seeds.append((sym,))

    def grow(prefix: tuple[str, ...]) -> None:
        if len(prefix) >= max_pattern_length:
            return
        for sym in vocabulary:
            candidate = prefix + (sym,)
            hits = support_of(candidate)
            if len(hits) >= min_support:
                frequent[candidate] = hits
                grow(candidate)

    for seed in seeds:
        grow(seed)
    return frequent
