"""Tests for the provenance-aware relational evaluation engine.

Expected polynomials are hand-derived per the semiring rules:

* repeated derivations of the same answer add,
* each join binding multiplies its witnesses,
* a row joined with itself keeps the squared witness (x*x = x^2).

Numeric cross-checks use an *independent* naive weighted enumerator defined in
this test module (it never imports the engine), so expected numbers are not
generated by the code under test.
"""
import pytest

from app.provenance import language
from app.provenance.engine import evaluate
from app.provenance.expressions import Polynomial
from app.provenance.store import InputRow, RelationData


# ---------------------------------------------------------------------------
# Independent reference: naive bag semantics with weighted inputs.
# Plain Python loops over in-memory rows; shares no code with the engine.
# ---------------------------------------------------------------------------

def _scan(rel: RelationData):
    return [(dict(zip(rel.columns, row.values)), row.row_id, row.weight)
            for row in rel.rows]


def _weighted_select(rows, col, op, const):
    import operator
    ops = {"=": operator.eq, "!=": operator.ne, "<": operator.lt,
           "<=": operator.le, ">": operator.gt, ">=": operator.ge}
    out = {}
    for vals, wid, w in rows:
        v = vals[col]
        if v is None:
            continue
        try:
            keep = ops[op](v, const)
        except TypeError:
            keep = False
        if keep:
            key = tuple(vals[c] for c in sorted(vals))
            out[key] = out.get(key, 0) + w
    return out


def _weighted_join(rel_l, rel_r, pairs, out_cols):
    acc = {}
    for l, wl in [(r.values, r.weight) for r in rel_l.rows]:
        lmap = dict(zip(rel_l.columns, l))
        for r, wr in [(r.values, r.weight) for r in rel_r.rows]:
            rmap = dict(zip(rel_r.columns, r))
            ok = True
            for lc, rc in pairs:
                a, b = lmap[lc], rmap[rc]
                if a is None or b is None or a != b:
                    ok = False
                    break
            if ok:
                merged = {**{f"l.{k}": v for k, v in lmap.items()},
                          **{f"r.{k}": v for k, v in rmap.items()}}
                key = tuple(merged[c] for c in out_cols)
                acc[key] = acc.get(key, 0) + wl * wr
    return acc


def _poly_map(result):
    return {row.values: row.provenance for row in result.rows}


def _dataset(tmp_store_rows):
    """Build {relation: RelationData} from (name, cols, InputRow...)."""
    out = {}
    for name, cols, rows in tmp_store_rows:
        out[name] = RelationData(name=name, columns=cols, rows=tuple(rows))
    return out


