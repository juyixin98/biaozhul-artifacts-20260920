"""High-precision reference values via mpmath.

This module is deliberately independent of the package under test: it uses
mpmath's own arbitrary-precision ``expm`` (scaling-and-squaring in mp
arithmetic) at 50 decimal digits, never the Krylov kernel.  Reference
vectors are therefore generated by a *different* implementation.
"""

from __future__ import annotations

import mpmath as mp
import numpy as np
import scipy.sparse as sp

MP_DPS = 50


def reference_expv(A: sp.spmatrix, t: float, v: np.ndarray, dps: int = MP_DPS) -> np.ndarray:
    """Compute exp(t*A) @ v in arbitrary precision."""
    old_dps = mp.mp.dps
    mp.mp.dps = dps
    try:
        dense = A.toarray()
        M = mp.matrix(dense.tolist())
        w = mp.expm(mp.mpf(repr(float(t))) * M) * mp.matrix(v.tolist())
        return np.array([float(x) for x in w], dtype=np.float64)
    finally:
        mp.mp.dps = old_dps


def relative_error(computed: np.ndarray, reference: np.ndarray) -> float:
    denom = float(np.linalg.norm(reference))
    if denom == 0.0:
        return float(np.linalg.norm(computed))
    return float(np.linalg.norm(computed - reference) / denom)
