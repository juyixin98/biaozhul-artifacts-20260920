"""Independent brute-force oracle used ONLY by tests.

This deliberately reimplements support counting from raw rows with naive
loops and set semantics, without importing anything from ``app.mining`` /
``app.apriori`` / ``app.indices``. Together with the hand-computed fractions
in ``expected_metrics.json`` and the optional mlxtend cross-check it ensures
expected answers are not generated by the implementation under test.
"""
from __future__ import annotations

from fractions import Fraction
from typing import Dict, FrozenSet, Iterable, Sequence, Tuple

# Metric results as exact fractions so floating point never decides a test.
ExactMetrics = Dict[str, Fraction | None]


def normalize_row(row: Sequence[str]) -> FrozenSet[str]:
    return {str(x).strip() for x in row if x is not None and str(x).strip()}


def normalized_transactions(raw: Iterable[Sequence[str]]) -> Tuple[FrozenSet[str], ...]:
    out = []
    for row in raw:
        items = normalize_row(row)
        if items:  # empty rows are dropped, mirroring corpus spec
            out.append(frozenset(items))
    return tuple(out)


def count_containing(txns: Sequence[FrozenSet[str]], items: Iterable[str]) -> int:
    wanted = frozenset(items)
    return sum(1 for t in txns if wanted <= t)


def exact_metrics(
    txns: Sequence[FrozenSet[str]],
    antecedent: Sequence[str],
    consequent: Sequence[str],
) -> ExactMetrics:
    n = len(txns)
    a = frozenset(antecedent)
    c = frozenset(consequent)
    n_a = count_containing(txns, a)
    n_c = count_containing(txns, c)
    n_u = count_containing(txns, a | c)

    support = Fraction(n_u, n)
    confidence = None if n_a == 0 else Fraction(n_u, n_a)
    lift = None if n_a * n_c == 0 else Fraction(n * n_u, n_a * n_c)
    leverage = Fraction(n_u, n) - Fraction(n_a * n_c, n * n)
    return {
        "support": support,
        "confidence": confidence,
        "lift": lift,
        "leverage": leverage,
        "n_a": n_a,
        "n_c": n_c,
        "n_u": n_u,
    }
