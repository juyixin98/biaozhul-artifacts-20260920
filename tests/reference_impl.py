"""Independent reference implementation for cross-checking the core.

Deliberately written from the metric *formulas* with exact Fraction
arithmetic, importing nothing from ``app.mining`` — reference answers must
not be generated by the implementation under test.
"""
from __future__ import annotations

from fractions import Fraction
from itertools import combinations


def support_count(transactions: list[frozenset[str]], items: frozenset[str]) -> int:
    return sum(1 for tx in transactions if items <= tx)


def all_frequent_itemsets(
    transactions: list[frozenset[str]], min_support: Fraction
) -> dict[frozenset[str], int]:
    """Brute-force: enumerate the full powerset of the item universe."""
    universe = sorted({i for tx in transactions for i in tx})
    n = len(transactions)
    out: dict[frozenset[str], int] = {}
    for size in range(1, len(universe) + 1):
        for combo in combinations(universe, size):
            cand = frozenset(combo)
            c = support_count(transactions, cand)
            if Fraction(c, n) >= min_support:
                out[cand] = c
    return out


def metrics(
    transactions: list[frozenset[str]],
    antecedent: frozenset[str],
    consequent: frozenset[str],
) -> dict:
    """Exact metrics; None where the denominator is zero (undefined)."""
    n = len(transactions)
    ca = support_count(transactions, antecedent)
    cb = support_count(transactions, consequent)
    cab = support_count(transactions, antecedent | consequent)
    confidence = Fraction(cab, ca) if ca > 0 else None
    lift = confidence / Fraction(cb, n) if (confidence is not None and cb > 0) else None
    return {
        "support": Fraction(cab, n),
        "confidence": confidence,
        "lift": lift,
        "leverage": Fraction(cab, n) - Fraction(ca, n) * Fraction(cb, n),
    }


def all_rules(
    transactions: list[frozenset[str]],
    frequent: dict[frozenset[str], int],
    min_confidence: Fraction,
) -> list[tuple[frozenset[str], frozenset[str]]]:
    """Exhaustive rule enumeration (no pruning) over frequent itemsets."""
    out = []
    for itemset in frequent:
        if len(itemset) < 2:
            continue
        items = sorted(itemset)
        for r in range(1, len(items)):
            for cons in combinations(items, r):
                cons = frozenset(cons)
                ante = itemset - cons
                m = metrics(transactions, ante, cons)
                if m["confidence"] is not None and m["confidence"] >= min_confidence:
                    out.append((ante, cons))
    return sorted(out, key=lambda rc: (sorted(rc[0]), sorted(rc[1])))
