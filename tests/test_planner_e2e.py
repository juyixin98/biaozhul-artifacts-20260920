"""End-to-end planner + evidence-store tests with hand-derived references.

The headline case is the two-hop self-join path over the graph fixture. The
expected polynomials below were worked out by hand from the fixture (not
generated by the engine), and they simultaneously exercise:

* duplicate input rows  e1 and e3 both being (a,b) -> additive terms,
* the self-loop tuple   e6 = (d,d) pairing with itself -> edge.e6**2,
* the NULL tuple        e5 = (a,NULL) being excluded (3-valued logic),
* answer + provenance coming from a single pinned version.
"""
from __future__ import annotations

import pytest

from provenance.errors import InputVersionError, PlanError
from provenance.evidence_store import Snapshot
from provenance.polynomial import Poly, mono

TWO_HOP_PLAN = {
    "op": "project",
    "columns": ["x.src", "y.dst"],
    "child": {
        "op": "join",
        "left": {"op": "relation", "name": "edge", "version": "v1", "alias": "x"},
        "right": {"op": "relation", "name": "edge", "version": "v1", "alias": "y"},
        "predicates": [{"op": "=", "left": "x.dst", "right": "y.src"}],
    },
}


def _by_key(result):
    return {(row.values["src"], row.values["dst"]): row for row in result.rows}


def test_two_hop_self_join_hand_derived(planner):
    result = planner.run(TWO_HOP_PLAN, request_id="req-2hop")

    assert result.version == "v1"
    rows = _by_key(result)
    assert set(rows) == {("a", "c"), ("b", "d"), ("c", "d"), ("d", "d")}

    # (a,c) reachable via e1->e2 and the duplicate-content tuple e3->e2.
    assert rows[("a", "c")].multiplicity == 2
    assert rows[("a", "c")].poly == Poly(
        [(mono("edge.e1", "edge.e2"), 1), (mono("edge.e2", "edge.e3"), 1)]
    )

    # Single-chain paths.
    assert rows[("b", "d")].poly == Poly({mono("edge.e2", "edge.e4"): 1})
    assert rows[("c", "d")].poly == Poly({mono("edge.e4", "edge.e6"): 1})

    # Self-loop d->d pairs the SAME tuple with itself -> variable squared.
    assert rows[("d", "d")].multiplicity == 1
    assert rows[("d", "d")].poly == Poly({mono("edge.e6", "edge.e6"): 1})
    assert rows[("d", "d")].poly.to_string() == "edge.e6**2"


def test_every_derivation_uses_only_fixture_variables(planner):
    result = planner.run(TWO_HOP_PLAN, request_id="req-vars")
    allowed = {f"edge.e{i}" for i in range(1, 7)}
    for row in result.rows:
        assert row.poly.variables() <= allowed


def test_answer_and_provenance_persisted_together(store, planner):
    planner.run(TWO_HOP_PLAN, request_id="req-persist")
    record = store.read_back("req-persist")
    assert record is not None
    assert record["status"] == "completed"
    assert record["versions"] == ["v1"]
    # The persisted multiplicity equals the all-ones evaluation of stored poly.
    for row in record["rows"]:
        total = sum(term["coeff"] for term in row["poly"])
        assert total == row["multiplicity"]


def test_mixed_versions_rejected(store, planner):
    # Introduce a second, independently versioned snapshot.
    store.load_snapshot(
        Snapshot.from_dict(
            {
                "version": "v2",
                "relations": {
                    "edge": {
                        "columns": ["src", "dst"],
                        "rows": [{"id": "z1", "data": {"src": "q", "dst": "r"}}],
                    }
                },
            }
        )
    )
    plan = {
        "op": "join",
        "left": {"op": "relation", "name": "edge", "version": "v1", "alias": "x"},
        "right": {"op": "relation", "name": "edge", "version": "v2", "alias": "y"},
        "predicates": [{"op": "=", "left": "x.dst", "right": "y.src"}],
    }
    with pytest.raises(InputVersionError) as exc:
        planner.run(plan, request_id="req-mixed")
    assert exc.value.category == "rejected_input_version"
    assert set(exc.value.details["versions"]) == {"v1", "v2"}


def test_missing_relation_version_rejected(planner):
    plan = {"op": "relation", "name": "ghost", "version": "v1"}
    with pytest.raises(InputVersionError) as exc:
        planner.run(plan, request_id="req-missing")
    assert exc.value.category == "rejected_input_version"


def test_unknown_column_rejected(planner):
    plan = {
        "op": "select",
        "child": {"op": "relation", "name": "edge", "version": "v1"},
        "predicates": [{"op": "=", "left": "nope", "literal": "a"}],
    }
    with pytest.raises(PlanError) as exc:
        planner.run(plan, request_id="req-col")
    assert exc.value.category == "rejected_plan"


def test_select_join_project_pipeline(planner):
    # src='a' edges joined to labels on dst=node, then project (dst,kind).
    plan = {
        "op": "project",
        "columns": ["edge.dst", "label.kind"],
        "child": {
            "op": "join",
            "left": {
                "op": "select",
                "child": {"op": "relation", "name": "edge", "version": "v1"},
                "predicates": [{"op": "=", "left": "src", "literal": "a"}],
            },
            "right": {"op": "relation", "name": "label", "version": "v1"},
            "predicates": [{"op": "=", "left": "edge.dst", "right": "label.node"}],
        },
    }
    result = planner.run(plan, request_id="req-pipe")
    rows = {
        (row.values["dst"], row.values["kind"]): row for row in result.rows
    }
    # e1 and e3 (both a,b) each join l2(b,mid); e5 (a,NULL) drops on the join.
    assert set(rows) == {("b", "mid")}
    row = rows[("b", "mid")]
    assert row.multiplicity == 2
    assert row.poly == Poly(
        [(mono("edge.e1", "label.l2"), 1), (mono("edge.e3", "label.l2"), 1)]
    )


def test_union_is_additive(planner):
    plan = {
        "op": "union",
        "left": {"op": "relation", "name": "edge", "version": "v1"},
        "right": {"op": "relation", "name": "redge", "version": "v1"},
    }
    result = planner.run(plan, request_id="req-union")
    rows = {(row.values["src"], row.values["dst"]): row for row in result.rows}
    # Duplicate-content edge tuples add; content unique across the two relations.
    assert rows[("a", "b")].poly == Poly(
        [(mono("edge.e1"), 1), (mono("edge.e3"), 1)]
    )
    assert rows[("b", "a")].poly == Poly.var("redge.r1")
    # NULL tuple survives a plain union (no predicate).
    assert ("a", None) in rows


def test_diagnostics_carry_request_id_and_outcomes(planner, log_stream):
    planner.run(TWO_HOP_PLAN, request_id="req-diag")
    logs = log_stream.getvalue()
    assert "req-diag" in logs
    assert '"outcome": "accepted"' in logs
    # The NULL pairing e5 (a,NULL) is judged indeterminable.
    assert '"outcome": "indeterminable"' in logs


def test_payload_includes_canonical_terms(planner):
    result = planner.run(TWO_HOP_PLAN, request_id="req-payload")
    payload = result.to_payload()
    squared = next(
        row for row in payload["rows"] if row["output"] == {"src": "d", "dst": "d"}
    )
    assert squared["provenance"] == "edge.e6**2"
    assert squared["provenance_terms"] == [{"vars": {"edge.e6": 2}, "coeff": 1}]
