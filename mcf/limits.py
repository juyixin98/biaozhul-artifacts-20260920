"""输入范围、容量上限与数值常量。

所有容量、费用、流量均为 **精确整数**，计算中不使用任何浮点运算，
因此不存在浮点容差问题（EPS = 0）。距离数组使用 NumPy ``int64`` 存储，
``DIST_INF`` 取一个远大于任何可达距离、但远离 int64 边界的哨兵值。
"""

from __future__ import annotations

# ---- 规模限制（小中规模）---------------------------------------------------
MAX_NODES = 2000          # 顶点数上限（含源、汇）
MAX_EDGES = 10_000        # 用户提供的有向边（弧）条数上限
MAX_REQUIRED_FLOW = 10**15  # 请求流量（required_flow）上限

# ---- 单条边数值范围 ---------------------------------------------------------
MIN_CAPACITY = 0
MAX_CAPACITY = 10**9      # 单弧容量 ∈ [0, 10^9]
MIN_COST = -(10**6)       # 单弧单位费用 ∈ [-10^6, 10^6]
MAX_COST = 10**6

# ---- 总费用安全界 -----------------------------------------------------------
# |总费用| 不超过 MAX_EDGES * MAX_CAPACITY * MAX_COST = 10^19，会溢出 int64。
# 算法中累计费用使用 Python 任意精度整数；只有被声明为“安全”的图
# （界 ≤ INT64_SAFE_COST_BOUND）才允许在 int64 距离数组中做加法而无溢出风险。
INT64_SAFE_COST_BOUND = 4 * 10**18  # 略小于 int64 最大值 9.22e18

# ---- 距离哨兵 ---------------------------------------------------------------
# 任何可达距离的绝对值至多为 (n-1)*MAX_COST ≤ 2000*1e6 = 2e9；
# 势函数同样如此。取 10^15 远大于真实距离，且 DIST_INF + 2e9 不溢出 int64。
DIST_INF = 10**15

# ---- 数值容差 ---------------------------------------------------------------
# 全部整数精确比较：约等容差为 0。保留该常量仅为在文档/响应中显式声明。
EPS = 0
