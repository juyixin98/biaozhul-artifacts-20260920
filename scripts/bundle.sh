#!/usr/bin/env bash
# Concatenate all manifests into the single-file installer config/install.yaml.
set -euo pipefail
cd "$(dirname "$0")/.."

out=config/install.yaml
{
  echo "# Generated by scripts/bundle.sh -- do not edit by hand."
  echo "# Sources: config/namespace.yaml config/crd/*.yaml config/rbac.yaml config/webhook/manifests.yaml config/manager.yaml"
  for f in config/namespace.yaml config/crd/*.yaml config/rbac.yaml config/webhook/manifests.yaml config/manager.yaml; do
    echo "---"
    cat "$f"
  done
} > "$out"
echo "wrote $out"
