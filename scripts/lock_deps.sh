#!/usr/bin/env bash
# Regenerate deps.lock from the versions actually found by the system
# package manager and CMake. Run from the repository root.
set -eu

OUT=deps.lock
{
  echo "# Locked dependency versions for the pose graph backend."
  echo "# Generated by scripts/lock_deps.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# Regenerate after upgrading the toolchain; CMake enforces minimum versions."
  echo
  echo "## build toolchain"
  printf 'cxx=%s\n' "$(g++ -dumpfullversion -dumpversion 2>/dev/null || g++ -dumpversion)"
  printf 'cmake=%s\n' "$(cmake --version | head -1 | awk '{print $3}')"
  echo
  echo "## libraries (dpkg)"
  for pkg in libceres-dev libeigen3-dev libsqlite3-dev libsuitesparse-dev; do
    v=$(dpkg-query -W -f='${Version}' "$pkg" 2>/dev/null || echo "NOT-INSTALLED")
    printf '%s=%s\n' "$pkg" "$v"
  done
  echo
  echo "## resolved cmake packages"
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  cat > "$tmp/CMakeLists.txt" <<'EOF'
cmake_minimum_required(VERSION 3.16)
project(v LANGUAGES CXX)
find_package(Ceres REQUIRED CONFIG)
find_package(Eigen3 REQUIRED NO_MODULE)
find_package(SQLite3 REQUIRED)
message(STATUS "LOCK_CERES_VERSION=${Ceres_VERSION}")
message(STATUS "LOCK_SQLITE3_VERSION=${SQLite3_VERSION}")
EOF
  cmake -S "$tmp" -B "$tmp/build" 2>&1 | grep -o 'LOCK_[A-Z0-9_]*=[0-9.]*' \
    | sed 's/LOCK_CERES_VERSION/ceres_cmake/;s/LOCK_SQLITE3_VERSION/sqlite3_cmake/'
} > "$OUT"

echo "wrote $OUT"
cat "$OUT"
